lines = text.split('\n')
rows = []
start = False
for line in lines:
    line = line.strip()
    if 'Row Labels' in line and 'Sum of Pay' in line:
        start = True
        continue
    if not start:
        continue
    if 'Grand Total' in line:
        break
    if not line:
        continue
    parts = line.split('\t')
    if len(parts) >= 4:
        loc = parts[0].strip()
        try:
            pay = int(parts[1].replace(',', '').strip())
            free = int(parts[2].replace(',', '').strip())
            camp = int(parts[3].replace(',', '').strip())
            rows.append((loc, pay, free, camp))
        except ValueError:
            pass

# Check math totals
total_pay = sum(r[1] for r in rows)
total_free = sum(r[2] for r in rows)
total_camp = sum(r[3] for r in rows)
total_combined = total_pay + total_free + total_camp

